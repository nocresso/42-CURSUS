#include "push_swap.h"

int	valid_number(char *str)
{
	int	i;

	i = 0;
	if (!str[i])
		return (0);
	if ((str[0] == '-' || str[0] == '+'))
	{
		if (!(str[1] >= '0' && str[1] <= '9'))
			return (0);
		i++;
	}
	while (str[i])
	{
		if (str[i] < '0' || str[i] > '9')
			return (0);
		i++;
	}
	return (1);
}
